//! ElevenLabs TTS synthesis service.
//!
//! Converts a grounding prompt into a calm, whisper-style MP3 audio file
//! via ElevenLabs streaming TTS API. Stores the audio as a temporary file
//! served by the Axum file server, auto-deleted after 60 seconds.

use std::path::PathBuf;
use std::time::Duration;

use serde::{Deserialize, Serialize};
use serde_json::json;
use tracing::{info, warn};
use uuid::Uuid;

use crate::config::AppConfig;
use crate::handlers::AppError;

/// Result of TTS synthesis.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TtsResult {
    /// Public URL path to synthesized audio (empty string if speech was not generated).
    pub audio_url: String,
    /// True if audio was generated by ElevenLabs, false if skipped or failed.
    pub is_synthesized: bool,
}

/// Synthesize speech from text and return the synthesis result.
pub async fn synthesize(text: &str, config: &AppConfig) -> Result<TtsResult, AppError> {
    if config.elevenlabs_api_key.trim().is_empty() {
        info!("ElevenLabs API key not set — skipping TTS synthesis (honest provider reporting)");
        return Ok(TtsResult {
            audio_url: String::new(),
            is_synthesized: false,
        });
    }

    // Ensure temp directory exists
    let dir = PathBuf::from(&config.audio_temp_dir);
    tokio::fs::create_dir_all(&dir)
        .await
        .map_err(|e| AppError::internal(format!("Failed to create audio temp dir: {}", e)))?;

    let audio_id = Uuid::new_v4();
    let filename = format!("{}.mp3", audio_id);
    let file_path = dir.join(&filename);
    let url_path = format!("/audio/{}", filename);

    match call_elevenlabs_api(text, config, &file_path).await {
        Ok(()) => {
            info!(file = %filename, "ElevenLabs TTS synthesis complete");

            // Schedule auto-cleanup after 60 seconds
            let cleanup_path = file_path;
            tokio::spawn(async move {
                tokio::time::sleep(Duration::from_secs(60)).await;
                if let Err(e) = tokio::fs::remove_file(&cleanup_path).await {
                    warn!(
                        "Failed to clean up temp audio file {:?}: {}",
                        cleanup_path, e
                    );
                } else {
                    info!("Cleaned up temp audio file {:?}", cleanup_path);
                }
            });

            Ok(TtsResult {
                audio_url: url_path,
                is_synthesized: true,
            })
        }
        Err(e) => {
            warn!(
                "ElevenLabs API call failed: {}. Reporting synthesis unavailable.",
                e
            );
            Ok(TtsResult {
                audio_url: String::new(),
                is_synthesized: false,
            })
        }
    }
}

/// Call ElevenLabs `/v1/text-to-speech/{voice_id}` and stream response to file.
async fn call_elevenlabs_api(
    text: &str,
    config: &AppConfig,
    output_path: &PathBuf,
) -> Result<(), anyhow::Error> {
    let url = format!(
        "https://api.elevenlabs.io/v1/text-to-speech/{}",
        config.elevenlabs_voice_id
    );

    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(15))
        .build()?;

    let payload = json!({
        "text": text,
        "model_id": "eleven_turbo_v2",
        "voice_settings": {
            "stability": 0.9,
            "similarity_boost": 0.5,
            "style": 0.0,
            "use_speaker_boost": false
        }
    });

    let bytes = client
        .post(&url)
        .header("xi-api-key", &config.elevenlabs_api_key)
        .header("Content-Type", "application/json")
        .header("Accept", "audio/mpeg")
        .json(&payload)
        .send()
        .await?
        .error_for_status()?
        .bytes()
        .await?;

    tokio::fs::write(output_path, &bytes).await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn test_synthesize_empty_key_reports_clean_non_synthesized() {
        let config = AppConfig {
            port: 8080,
            gemma_api_key: String::new(),
            gemma_model: "gemma-2b-it".to_string(),
            elevenlabs_api_key: String::new(),
            elevenlabs_voice_id: "test".to_string(),
            tabpfn_api_key: String::new(),
            tabpfn_endpoint: "https://api.priorlabs.ai".to_string(),
            audio_temp_dir: std::env::temp_dir().to_string_lossy().to_string(),
        };

        let result = synthesize("Step outside into the breeze.", &config)
            .await
            .unwrap();
        assert_eq!(result.audio_url, "");
        assert!(!result.is_synthesized);
    }
}
